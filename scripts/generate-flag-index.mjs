import { execFileSync } from "node:child_process";
import { createRequire } from "node:module";
import { lstatSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

process.env.FEATURE_FLAG_TYPESCRIPT_PATH = createRequire(import.meta.url).resolve("typescript");
const { FLAG_DEFINITIONS_DIRECTORY, parseFlagFiles } = await import("../.github/scripts/feature-flag-registry.mjs");

export function productionFlagReleases(root, env = process.env, git = execFileSync) {
  if (env.VERCEL_ENV !== "production" || env.VERCEL_GIT_COMMIT_REF !== "production"
    || !/^[a-f0-9]{40}$/.test(env.VERCEL_GIT_COMMIT_SHA ?? "")) return {};
  const options = { cwd: root, encoding: "utf8", timeout: 10_000 };
  let log;
  try {
    if (git("git", ["rev-parse", "HEAD"], options).trim() !== env.VERCEL_GIT_COMMIT_SHA) {
      throw new Error("Production flag metadata must match the deployed commit");
    }
    log = git("git", ["log", "HEAD", "--min-parents=1", "--first-parent", "--diff-merges=first-parent", "--diff-filter=A", "--since=2 hours ago", "--format=%ct", "--name-only", "--", FLAG_DEFINITIONS_DIRECTORY], options);
  } catch {
    console.warn("Production flag release history unavailable or mismatched; default-on flags will not be enrolled");
    return {};
  }
  const releases = {};
  let releasedAt;
  for (const line of log.split("\n")) {
    if (/^\d+$/.test(line)) releasedAt = new Date(Number(line) * 1000).toISOString();
    const match = /^src\/lib\/flags\/definitions\/(htpr-[1-9]\d*-[a-z0-9]+(?:-[a-z0-9]+)*)\.ts$/.exec(line);
    if (match && releasedAt && !releases[match[1]]) releases[match[1]] = releasedAt;
  }
  return releases;
}

export function generateFlagIndex(root = process.cwd()) {
  const directory = path.join(root, FLAG_DEFINITIONS_DIRECTORY);
  const output = path.join(directory, "index.generated.ts");
  // Trusted CI runs this on a pull request checkout: read regular files only, never follow links.
  const ancestors = FLAG_DEFINITIONS_DIRECTORY.split("/").filter(Boolean)
    .map((_, index, parts) => path.join(root, ...parts.slice(0, index + 1)));
  for (const ancestor of ancestors) {
    const stat = lstatSync(ancestor);
    if (stat.isSymbolicLink() || !stat.isDirectory()) throw new Error(`${path.relative(root, ancestor)} must be a regular directory`);
  }
  const names = readdirSync(directory).filter((name) => name !== "index.generated.ts").sort();
  for (const target of [directory, output, ...names.map((name) => path.join(directory, name))]) {
    let stat;
    try { stat = lstatSync(target); } catch (error) { if (error.code === "ENOENT" && target === output) continue; throw error; }
    if (stat.isSymbolicLink() || (target === directory ? !stat.isDirectory() : !stat.isFile())) {
      throw new Error(`${path.relative(root, target)} must be a regular ${target === directory ? "directory" : "file"}`);
    }
  }
  const paths = names.map((name) => FLAG_DEFINITIONS_DIRECTORY + name);
  const rows = parseFlagFiles(paths, (name) => readFileSync(path.join(root, name), "utf8"));
  const text = [
    "// Generated by scripts/generate-flag-index.mjs. Do not commit or edit.",
    ...rows.map(({ definition }, index) => `import flag${index} from "./${definition.key}";`),
    "",
    ...rows.map(({ identifier, definition }) => `export { ${identifier} } from "./${definition.key}";`),
    "",
    "export const FLAG_DEFINITIONS = [",
    ...rows.map((_, index) => `  flag${index},`),
    "] as const;",
    "",
    `export const PRODUCTION_FLAG_RELEASES: Readonly<Record<string, string>> = ${JSON.stringify(productionFlagReleases(root))};`,
    "",
  ].join("\n");
  let existing;
  try { existing = readFileSync(output, "utf8"); } catch (error) { if (error.code !== "ENOENT") throw error; }
  if (text !== existing) writeFileSync(output, text);
  console.log(`Generated flag index (${rows.length} flags)`);
  return text;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === path.resolve(process.argv[1])) {
  generateFlagIndex(process.argv[2] ? path.resolve(process.argv[2]) : process.cwd());
}
