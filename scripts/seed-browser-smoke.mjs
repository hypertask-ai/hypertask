async function createBoard({ ownerId, teamId, googleAccountId, title, suffix, longThread = false }) {
  const sectionTitles = ["To do", "Done"];
  const project = await prisma.project.create({
    data: {
      name: visual ? `visual-${suffix}` : `browser-smoke-${suffix}-${runKey}`,
      ...(visual ? { createdAt: new Date(VISUAL_NOW) } : {}),
      title,
      ownerId,
      teamId,
      googleAccountId,
      uniqueIdentifier: suffix.toUpperCase(),
      sections: sectionTitles,
    },
  });
  const sections = await Promise.all(
    sectionTitles.map((sectionTitle, index) =>
      prisma.section.create({
        data: {
          projectId: project.id,
          section_title: sectionTitle,
          ranking: index === 0 ? "A0100" : "A0200",
          isDone: index === 1,
        },
      }),
    ),
  );
  await prisma.member.create({
    data: { projectId: project.id, userId: ownerId },
  });
  const task = await prisma.task.create({
    data: {
      uniqueIndex: 1,
      ticketNumber: `${suffix.toUpperCase()}-1`,
      title: `${title} fixture`,
      updatedAt: new Date(visual ? VISUAL_NOW : Date.now()),
      ...(visual ? { createdAt: new Date(VISUAL_NOW), sectionChangedAt: new Date(VISUAL_NOW) } : {}),
      description: "",
      description_: {
        create: { content: "<p>This seeded ticket must open from its board card.</p>", creatorId: ownerId },
      },
      projectId: project.id,
      userId: ownerId,
      section: sections[0].section_title,
      sectionId: sections[0].id,
      ranking: "A0100",
    },
  });
  await prisma.comment.createMany({
    data: ["First layout lock comment", "Last layout lock comment"].map((text, index) => ({
      taskId: task.id,
      creatorId: ownerId,
      text: `<p>${text}</p>`,
      commentText: text,
      createdAt: new Date((visual ? Date.parse(VISUAL_NOW) : Date.now()) - (2 - index) * 60_000),
    })),
  });
  // HTPR-7074: the CLS test gets its own board, so the layout-lock fixture ticket stays exactly as it was.
  if (longThread) {
    await prisma.comment.createMany({
      data: Array.from({ length: 6 }, (_, index) => ({
        taskId: task.id,
        creatorId: ownerId,
        text: [1, 2].map((paragraph) => `<p>Long thread comment ${index + 1}, paragraph ${paragraph}. The quick brown fox jumps over the lazy dog, then keeps going so this paragraph wraps onto several lines in the thread.</p>`).join(""),
        commentText: `Long thread comment ${index + 1}`,
        createdAt: new Date((visual ? Date.parse(VISUAL_NOW) : Date.now()) - (9 - index) * 60_000),
      })),
    });
  }
  return { ...project, task, columns: sections.map(section => ({ id: section.id, title: section.section_title })) };
}

async function seedSessionFixtures(flags) {
  const user = await prisma.user.create({
    data: {
      uid: visual ? "visual-regression-user" : `browser-smoke-${runKey}`,
      ...(visual ? { photoURL: null, joinedAt: new Date(VISUAL_NOW), updatedAt: new Date(VISUAL_NOW) } : {}),
      ...(localPremerge ? { id: 985 } : {}),
      email: visual ? "visual-user@example.invalid" : localPremerge ? "valentin@hypertask.ai" : `browser-smoke-${runKey}@example.invalid`,
      displayName: visual ? "Visual regression user" : "Browser smoke user",
      UserSetting: {
        create: {
          notification: false,
          onboardingTourStatus: true,
          onboardingTutorialStatus: true,
        },
      },
    },
    include: { UserSetting: true },
  });
  if (user.id === 6 || (!localPremerge && user.id === 985)) {
    throw new Error("Disposable browser smoke user received a reserved id");
  }
  if (!user.UserSetting) {
    throw new Error("Disposable browser smoke user has no settings");
  }
  await Promise.all([
    prisma.userPicture.create({
      data: {
        userId: user.id,
        displayName: user.displayName,
        basePhotoURL: user.photoURL,
      },
    }),
    prisma.user_Activity.create({
      data: {
        userId: user.id,
        totalTeamsOwned: 1,
        lastActiveAt: new Date(visual ? VISUAL_NOW : Date.now()),
      },
    }),
  ]);

  const googleAccount = await prisma.googleAccount.create({
    data: {
      userId: user.id,
      stripe_customer_id: `browser-smoke-${runKey}`,
    },
  });
  const team = await prisma.team.create({
    data: {
      title: "Browser smoke",
      totalSeats: 1,
      googleAccountId: googleAccount.id,
    },
  });
  await Promise.all([
    prisma.team_Activity.create({
      data: {
        teamId: team.id,
        lastActiviyAt: new Date(visual ? VISUAL_NOW : Date.now()),
      },
    }),
    prisma.member_Team.create({
      data: {
        userId: user.id,
        teamId: team.id,
        googleAccountId: googleAccount.id,
        status: "Accepted",
        acceptedAt: new Date(visual ? VISUAL_NOW : Date.now()),
      },
    }),
    prisma.user.update({
      where: { id: user.id },
      data: {
        accountId: googleAccount.id,
        UserSettingId: user.UserSetting.id,
        ...(visual ? { updatedAt: new Date(VISUAL_NOW) } : {}),
      },
    }),
  ]);

  const board = await createBoard({
    ownerId: user.id,
    teamId: team.id,
    googleAccountId: googleAccount.id,
    title: "Browser smoke board",
    suffix: "board",
  });
  const demoBoard = await createBoard({
    ownerId: user.id,
    teamId: team.id,
    googleAccountId: googleAccount.id,
    title: "Browser smoke demo board",
    suffix: "demo",
  });
  const threadBoard = await createBoard({
    ownerId: user.id,
    teamId: team.id,
    googleAccountId: googleAccount.id,
    title: "Browser smoke long thread board",
    suffix: "thread",
    longThread: true,
  });

  const sessionUser = await prisma.user.findUnique({
    where: { id: user.id },
    select: {
      id: true,
      uid: true,
      displayName: true,
      photoURL: true,
      email: true,
      joinedAt: true,
      UserSettingId: true,
      accountId: true,
      stripe_customer_id: true,
      UserSetting: true,
    },
  });
  if (!sessionUser) {
    throw new Error("Disposable browser smoke user disappeared");
  }

  const expires = Math.floor(Date.now() / 1000) + SESSION_TTL_SECONDS;
  const cookieBase = {
    domain: "127.0.0.1",
    path: "/",
    expires,
    secure: false,
    sameSite: "Lax",
  };
  const state = {
    cookies: [
      {
        ...cookieBase,
        name: "ht_session",
        value: signSession({ id: user.id, email: user.email }),
        httpOnly: true,
      },
      {
        ...cookieBase,
        name: "nookies_user",
        value: encodeURIComponent(
          JSON.stringify(sessionUser),
        ),
        httpOnly: false,
      },
      {
        ...cookieBase,
        name: "previousBoard",
        value: `project-${board.id}|&|`,
        httpOnly: false,
      },
    ],
    origins: [],
  };

  await mkdir(path.dirname(stateFile), { recursive: true });
  await writeFile(stateFile, JSON.stringify(state), {
    flag: "wx",
    mode: 0o600,
  });
  const { createMcpToken, agentTokenCredentialFields } = jiti(path.join(root, "src/lib/mcp/auth/verifyJwt.ts"));
  const sidebarLanes = {};
  for (const lane of ["Desktop", "Mobile"]) {
    const agents = [];
    for (const [suffix, runtimeType] of [["A", "EXTERNAL"], ["B", "EXTERNAL"], ["Native", "NATIVE"]]) {
      const agent = await prisma.agent.create({ data: {
        userId: user.id, displayName: `Sidebar ${lane} ${suffix}`, runtimeType,
        photoURL: null, visibility: "PRIVATE", prompt: runtimeType === "NATIVE" ? "Answer this user's board questions." : null,
      } });
      await prisma.member.create({ data: { projectId: board.id, userId: user.id, agentId: agent.id, status: "Accepted" } });
      const token = createMcpToken(user.id, user.email, "1h", agent.id);
      await prisma.agent.update({ where: { id: agent.id }, data: agentTokenCredentialFields(token) });
      const session = await prisma.chatSession.create({ data: { userId: user.id, agentId: agent.id, teamId: team.id, title: agent.displayName } });
      await prisma.chatMessage.createMany({ data: Array.from({ length: 30 }, (_, index) => ({
        sessionId: session.id, content: `${agent.displayName} history ${index + 1}`, role: "assistant", authorAgentId: agent.id, isDelivered: true,
      })) });
      agents.push({ id: agent.id, name: agent.displayName, sessionId: session.id, token });
    }
    sidebarLanes[lane] = agents;
  }
  await writeFile(path.join(path.dirname(stateFile), "agent-sidebar-fixture.json"), JSON.stringify({ projectId: board.id, lanes: sidebarLanes }), { flag: "wx", mode: 0o600 });
  let contract;
  if (contractEnabled) {
    const callers = {};
    let contractGoogleAccount, contractTeam;
    for (const role of ["owner", "member", "guest", "unaccepted"]) {
      const caller = await prisma.user.create({
        data: {
          uid: `contract-${role}-${runKey}`,
          email: `contract-${role}-${runKey}@example.invalid`,
          displayName: `Contract ${role}`,
          UserSetting: { create: { notification: false, onboardingTourStatus: true, onboardingTutorialStatus: true } },
        },
        include: { UserSetting: true },
      });
      if (role === "owner") {
        contractGoogleAccount = await prisma.googleAccount.create({ data: {
          userId: caller.id, stripe_customer_id: `contract-${runKey}`,
        } });
        contractTeam = await prisma.team.create({ data: {
          title: "MCP contract", totalSeats: 2, googleAccountId: contractGoogleAccount.id,
        } });
        await prisma.team_Activity.create({ data: { teamId: contractTeam.id, lastActiviyAt: new Date() } });
        await prisma.member_Team.create({ data: {
          userId: caller.id, teamId: contractTeam.id, googleAccountId: contractGoogleAccount.id,
          status: "Accepted", acceptedAt: new Date(),
        } });
        caller.accountId = contractGoogleAccount.id;
      }
      await prisma.user.update({ where: { id: caller.id }, data: {
        UserSettingId: caller.UserSetting.id, ...(role === "owner" ? { accountId: caller.accountId } : {}),
      } });
      await prisma.userPicture.create({ data: { userId: caller.id, displayName: caller.displayName } });
      await prisma.user_Activity.create({ data: { userId: caller.id, totalTeamsOwned: role === "owner" ? 1 : 0, lastActiveAt: new Date() } });
      callers[role] = { id: caller.id, cookies: [
        { name: "ht_session", value: signSession({ id: caller.id, email: caller.email }) },
        { name: "nookies_user", value: encodeURIComponent(JSON.stringify({ ...caller, UserSettingId: caller.UserSetting.id })) },
      ] };
    }
    await prisma.member_Team.create({ data: {
      userId: callers.member.id, teamId: contractTeam.id, googleAccountId: contractGoogleAccount.id,
      status: "Accepted", acceptedAt: new Date(),
    } });
    const boards = [];
    for (const suffix of ["contract", "contract-target"]) {
      const project = await createBoard({ ownerId: callers.owner.id, teamId: contractTeam.id, googleAccountId: contractGoogleAccount.id, title: `MCP contract ${suffix}`, suffix });
      await prisma.member.createMany({ data: ["member", "guest"].map(role => ({
        projectId: project.id, userId: callers[role].id, status: "Accepted",
        invitedAt: new Date(), acceptedAt: new Date(),
      })) });
      await prisma.invite.createMany({ data: ["guest", "unaccepted"].map(role => ({
        key: randomUUID(), userId: callers.owner.id, projectId: project.id,
        emails: [`contract-${role}-${runKey}@example.invalid`],
        uses: role === "guest" ? 0 : 1,
      })) });
      const label = await prisma.label.create({ data: { projectId: project.id, value: "Contract label" } });
      boards.push({ id: project.id, task: project.task, columns: project.columns, title: project.title, label: { id: label.id, name: label.value } });
    }
    // External guests have board membership only, never team membership.
    if (await prisma.member_Team.count({ where: { userId: { in: [callers.guest.id, callers.unaccepted.id] } } })) {
      throw new Error("Contract guest controls must not have team membership");
    }
    contract = { callers, boards, flags };
    await writeFile(path.join(path.dirname(stateFile), "contract-fixture.json"), JSON.stringify(contract), { flag: "wx", mode: 0o600 });
  }
  await writeFile(fixtureFile, JSON.stringify({
    ...(visual ? { visualNow: VISUAL_NOW, boardPath: `/project?id=${board.id}&surface=board` } : {}),
    taskId: board.task.id,
    title: board.task.title,
    description: "This seeded ticket must open from its board card.",
    detailPath: `/detail/project-${board.id}/${board.task.uniqueIndex}`,
    longThreadDetailPath: `/detail/project-${threadBoard.id}/${threadBoard.task.uniqueIndex}`,
    flags,
    ...((localPremerge || contractEnabled || visual) ? { searchRows: [board, demoBoard, ...(contract?.boards ?? [])].map(project => ({
      id: String(project.task.id),
      ticketNumber: project.task.ticketNumber,
      title: project.task.title,
      descriptionText: "This seeded ticket must open from its board card.",
      projectId: project.id,
      creatorName: user.displayName,
      status: project.task.status,
      updatedAt: project.task.updatedAt.toISOString(),
      searchText: project.task.title,
      uniqueIndex: project.task.uniqueIndex,
      projectTitle: project.title,
    })) } : {}),
  }));
  await appendFile(
    process.env.GITHUB_OUTPUT,
    `board_path=/project?id=${board.id}&surface=board\ndemo_board_path=/project?id=${demoBoard.id}&surface=board\n`,
  );
}

// YPER4-629: five fresh reminder messages on their own board, seeded only right before the inbox cycle spec
// so the layout lock runs still see an empty inbox. Flag modes are left exactly as the previous control set them.
async function seedInboxCycle() {
  const fixture = JSON.parse(await readFile(fixtureFile, "utf8"));
  const boardId = Number(/^\/detail\/project-(\d+)\//.exec(fixture.detailPath)?.[1]);
  const board = await prisma.project.findUnique({ where: { id: boardId }, select: { ownerId: true, teamId: true, googleAccountId: true } });
  if (!board) throw new Error("Inbox cycle needs the seeded board");
  const userId = board.ownerId;
  await prisma.notification.updateMany({ where: { userId, archivedAt: null }, data: { archivedAt: new Date() } });
  const { UserSettingId } = await prisma.user.findUniqueOrThrow({ where: { id: userId }, select: { UserSettingId: true } });
  await prisma.userSetting.update({ where: { id: UserSettingId }, data: { inboxAdvanceOnSend: true } });
  const inboxBoard = await createBoard({
    ownerId: userId,
    teamId: board.teamId,
    googleAccountId: board.googleAccountId,
    title: "Browser smoke inbox board",
    suffix: `inbox${randomUUID().slice(0, 6)}`,
  });
  const [todo] = inboxBoard.columns;
  const items = [];
  for (let index = 0; index < 5; index++) {
    const uniqueIndex = index + 2;
    const task = await prisma.task.create({
      data: {
        uniqueIndex,
        ticketNumber: `${inboxBoard.uniqueIdentifier}-${uniqueIndex}`,
        title: `Inbox cycle message ${index + 1}`,
        description: "",
        projectId: inboxBoard.id,
        userId,
        section: todo.title,
        sectionId: todo.id,
        ranking: `A0${300 + index}`,
      },
    });
    await prisma.notification.create({
      data: { type: "TaskReminder", userId, taskId: task.id, projectId: inboxBoard.id, createdAt: new Date(Date.now() - index * 60_000) },
    });
    items.push({ taskId: task.id, title: task.title, detailPath: `/detail/project-${inboxBoard.id}/${uniqueIndex}` });
  }
  await writeFile(path.join(path.dirname(stateFile), "inbox-cycle-fixture.json"), JSON.stringify({ items }), { mode: 0o600 });
}

try {
  if (inboxCycle) {
    await seedInboxCycle();
    console.log("Seeded inbox cycle fixtures.");
  } else {
  {
    // The generated copy can lag a new flag: a flag missing from it uses its registry default.
    const { FEATURE_FLAG_KEYS, defaultFeatureFlagMode } = jiti(path.join(root, "src/lib/flags.ts"));
    for (const key of FEATURE_FLAG_KEYS) modes[key] ??= defaultFeatureFlagMode(key);
  }
  if (allFlagsOn) {
    const { FEATURE_FLAG_KEYS } = jiti(path.join(root, "src/lib/flags.ts"));
    modes = Object.fromEntries(FEATURE_FLAG_KEYS.map(key => [key, "EVERYONE"]));
  } else if (liveLikeControl) {
    const { FEATURE_FLAG_KEYS } = jiti(path.join(root, "src/lib/flags.ts"));
    // Match the CI plain-user layout even when the local fixture is QA user 985.
    modes = Object.fromEntries(FEATURE_FLAG_KEYS.map(key => [key, modes[key] === "EVERYONE" ? "EVERYONE" : "OFF"]));
  } else if (localPremerge) {
    const { FEATURE_FLAG_KEYS, defaultFeatureFlagMode } = jiti(path.join(root, "src/lib/flags.ts"));
    const defaults = Object.fromEntries(FEATURE_FLAG_KEYS.map(key => [key, defaultFeatureFlagMode(key)]));
    const overrides = process.argv.slice(2);
    if (overrides.some((value, index) => index % 2 === 0 && value !== "--flag") || overrides.length % 2) {
      throw new Error("Invalid local flag arguments");
    }
    const plain = await readPlainQaFlags();
    const qa = await readPlainQaFlags(QA_ACCOUNT_STATE);
    // Loud, not silent: the committed copy is what browser checks and QA plans read.
    const live = localFlagModes(defaults, plain, [], qa);
    const drift = Object.keys(live).filter(key => key in modes && modes[key] !== live[key]).map(key => `${key}: file ${modes[key]}, live ${live[key]}`);
    if (drift.length) console.error(`WARNING: e2e/smoke/production-flag-modes.json differs from the live flag modes (${drift.length}). Using live. Fix: node scripts/flags/production-flag-modes.mjs --write\n${drift.join("\n")}`);
    modes = localFlagModes(defaults, plain, overrides.filter((_, index) => index % 2), qa);
    await writeFile(path.join(path.dirname(stateFile), "flag-modes.json"), JSON.stringify({ modes }));
  }
  // Controls reseed a running app, so invalidate its previous raw-mode snapshot.
  await withFlagModeInvalidation(async () => {
    for (const [key, mode] of Object.entries(modes)) {
      await prisma.featureFlag.upsert({ where: { key }, create: { key, mode }, update: { mode } });
    }
  });
  const flags = Object.fromEntries(Object.entries(modes).map(([key, mode]) => [key, mode === "EVERYONE" || (localPremerge && mode === "OWNER_AND_QA")]));
  if (instantOpenControl || allFlagsOn || liveLikeControl) {
    // Controls reuse the logged-in user and fixtures, changing only local flag rows.
    const fixture = JSON.parse(await readFile(fixtureFile, "utf8"));
    await writeFile(fixtureFile, JSON.stringify({ ...fixture, flags, allFlagsOn }));
  } else {
    await seedSessionFixtures(flags);
  }
  console.log("Seeded isolated browser smoke fixtures.");
  }
} finally {
  await prisma.$disconnect();
  if (process.env.REDIS_URL) {
    const { getRedis } = jiti(path.join(root, "src/lib/redis.ts"));
    (await getRedis()).disconnect();
  }
}
