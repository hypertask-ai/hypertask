import { readdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";

const OUT = "config/test-duration-weights.json";

async function findReports(directory) {
  const found = [];
  const entries = await readdir(directory, { withFileTypes: true });
  for (const entry of entries) {
    const absolute = path.join(directory, entry.name);
    if (entry.isDirectory()) found.push(...await findReports(absolute));
    else if (entry.name === "test-durations.json") found.push(absolute);
  }
  return found;
}

function median(values) {
  const sorted = [...values].sort((a, b) => a - b);
  const middle = Math.floor(sorted.length / 2);
  return sorted.length % 2 ? sorted[middle] : (sorted[middle - 1] + sorted[middle]) / 2;
}

function argValue(argv, flag) {
  const index = argv.indexOf(flag);
  return index < 0 ? undefined : argv[index + 1];
}

async function main() {
  const argv = process.argv.slice(2);
  const input = argValue(argv, "--input");
  if (!input) throw new Error("Usage: test-duration-weights.mjs --input DIR [--source TEXT] [--out FILE]");
  const reports = await findReports(input);
  if (reports.length < 2) throw new Error(`need at least two test-durations reports, found ${reports.length}`);

  const work = new Map();
  const pooled = [];
  for (const report of reports) {
    const parsed = JSON.parse(await readFile(report, "utf8"));
    for (const file of parsed.files) {
      const concurrency = Number(file.concurrency) || 1;
      const value = Number(file.durationMs) / concurrency;
      if (!Number.isFinite(value) || value < 0) throw new Error(`bad duration in ${report}`);
      if (!work.has(file.file)) work.set(file.file, []);
      work.get(file.file).push(value);
      if (concurrency > 1) pooled.push(value);
    }
    for (const file of parsed.sharedFiles ?? []) {
      const value = Number(file.testMs);
      if (!Number.isFinite(value) || value < 0) throw new Error(`bad shared duration in ${report}`);
      if (!work.has(file.file)) work.set(file.file, []);
      work.get(file.file).push(value);
    }
  }

  const files = {};
  for (const [file, values] of [...work].sort((a, b) => a[0].localeCompare(b[0]))) {
    files[file] = Math.round(median(values));
  }
  const output = {
    note: "Generated by scripts/test-duration-weights.mjs from real production ci-tests runs. Do not hand-edit.",
    source: argValue(argv, "--source") ?? `${reports.length} test-durations reports`,
    reports: reports.length,
    defaultWorkMs: Math.max(1, Math.round(median(pooled))),
    files,
  };
  const out = argValue(argv, "--out") ?? OUT;
  await writeFile(out, `${JSON.stringify(output, null, 1)}\n`);
  const total = Object.values(files).reduce((sum, value) => sum + value, 0);
  console.log(`weights ${out} files=${Object.keys(files).length} reports=${reports.length} totalWork=${(total / 1000).toFixed(0)}s defaultWorkMs=${output.defaultWorkMs}`);
}

main().catch((error) => {
  console.error(error.message);
  process.exit(1);
});
