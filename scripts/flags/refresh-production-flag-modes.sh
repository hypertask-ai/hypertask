#!/usr/bin/env bash
# Keeps e2e/smoke/production-flag-modes.json fresh. Runs on the VPS from a systemd timer, where the
# plain QA session is available, never in CI. It regenerates the per-flag files under
# e2e/smoke/flag-modes/ and the built copy in a throwaway worktree of origin/production and, only
# when either changed (modes, or capture older than 7 days), pushes
# branch flag-modes-refresh and opens or updates ONE pull request. It never merges anything.
# A missing QA session or a failed live read exits non-zero and changes nothing. A stale installed
# copy exits non-zero too: an out-of-date copy once committed the built file without its per-flag
# files (HTPR-8254).
set -euo pipefail
file=e2e/smoke/production-flag-modes.json
dir=e2e/smoke/flag-modes
pause="$HOME/.local/state/gh-shared-cache/pause-until"
if [ -r "$pause" ] && [ "$(date +%s)" -lt "$(tr -dc 0-9 < "$pause" | head -c 12 | sed 's/^$/0/')" ]; then
  echo "flag-modes-refresh: paused by gh-shared-cache pause-until, skipping"
  exit 0
fi
repo="${HYPERTASK_REPO:-$HOME/projects/hypertask}"
work="$(mktemp -d)"
trap 'git -C "$repo" worktree remove --force "$work" >/dev/null 2>&1 || true; rm -rf "$work"' EXIT
git -C "$repo" fetch -q origin production
installed=$(sha256sum "$0" | cut -d' ' -f1)
expected=$(git -C "$repo" show "origin/production:scripts/flags/refresh-production-flag-modes.sh" | sha256sum | cut -d' ' -f1)
if [ "$installed" != "$expected" ]; then
  echo "flag-modes-refresh: this installed copy is out of date (sha256 $installed, production $expected). Reinstall it from origin/production scripts/flags/refresh-production-flag-modes.sh; nothing changed" >&2
  exit 1
fi
git -C "$repo" worktree add -q --detach "$work" origin/production
cd "$work"
"$work/scripts/worktree-node-modules.sh" "$repo" "$work"
if ! node scripts/flags/production-flag-modes.mjs --write; then
  echo "flag-modes-refresh: FAILED to read the live switch settings (QA session cookie missing or expired, or the read failed); nothing changed" >&2
  exit 1
fi
committed_age=$(git show "origin/production:$file" | node -e 'let s="";process.stdin.on("data",d=>s+=d).on("end",()=>console.log(Math.floor((Date.now()-Date.parse(JSON.parse(s).capturedAt))/86400000)))')
git add -A -- "$dir"
if git diff --cached --quiet -I'"capturedAt"' -- "$dir" "$file" && [ "$committed_age" -lt 7 ]; then
  echo "flag-modes-refresh: live modes unchanged and the copy is $committed_age days old, nothing to do"
  for n in $(gh pr list --repo hypertask-ai/hypertask --head flag-modes-refresh --state open --json number --jq '.[].number'); do
    gh pr close "$n" --repo hypertask-ai/hypertask --delete-branch --comment "Live switch settings match production again; closing."
  done
  exit 0
fi
git checkout -q -B flag-modes-refresh
git add -A -- "$dir" "$file"
git commit -q -m "Refresh the live switch settings copy"
git push -q --force origin flag-modes-refresh
if [ -n "$(gh pr list --repo hypertask-ai/hypertask --head flag-modes-refresh --state open --json number --jq '.[].number')" ]; then
  echo "flag-modes-refresh: updated the open pull request"
  exit 0
fi
# No ticket prefix: the PR guard binds a ticket-shaped title, and the mechanism's ticket is done,
# so the binding is refused and this pull request can never go green (HTPR-8254).
body=$(printf '%s\n' '## Summary for non-engineers' '' 'This updates the copy of the live switch settings that the browser checks use. Nothing for Valentin to do.' '' 'It is generated by scripts/flags/production-flag-modes.mjs and refreshed by a timer every 6 hours.')
gh pr create --repo hypertask-ai/hypertask --base production --head flag-modes-refresh \
  --title "Refresh the live switch settings copy" --body "$body"
