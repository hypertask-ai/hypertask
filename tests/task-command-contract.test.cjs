const test = require('node:test')
const assert = require('node:assert/strict')
const path = require('node:path')
const root = path.resolve(__dirname, '..')
const jiti = require('jiti')(__filename, { alias: { '@': path.resolve(root, 'src') }, cache: false })
const tasks = require('../src/lib/mcp-server/config/descriptions/tasks.json')
const parameters = require('../src/lib/mcp-server/config/descriptions/parameters.json')
const { invalidTaskRelationTypeBody, normalizeTaskRelationType, taskRelationTypeHelp } = jiti('../src/lib/mcp/tasks/relationType.ts')
const { LinkTasksInputSchema } = jiti('../src/lib/mcp-server/validations/task.validation.ts')
const { validateTaskUpdateIdentifiers } = jiti('../src/lib/mcp/tasks/fields/validateIdentifiers.ts')
const { TOOL_METADATA } = jiti('../src/lib/mcp-server/config/tool-metadata.ts')

test('edit updates a ticket and relations lists its links', () => {
  assert.equal(tasks.actions.edit.tool, tasks.actions.update.tool)
  assert.equal(tasks.actions.edit.legacy_action, undefined)
  assert.equal(tasks.actions.relations.tool, tasks.actions.links.tool)
  assert.equal(tasks.actions.relations.legacy_action, 'list')
  assert.match(tasks.parameters_and_caveats, /edit is update/)
  assert.match(tasks.parameters_and_caveats, /relations lists links/)
  const description = `Does: ${tasks.does}\nUse when: ${tasks.use_when}\nDo not use when: ${tasks.do_not_use_when}\nParameters and caveats: ${tasks.parameters_and_caveats} board_id is an alias for project_id.`
  assert.ok(description.length < 1800, String(description.length))
})

test('link help names RelatedTo, BlockedBy and BlockedTo', () => {
  const body = invalidTaskRelationTypeBody()
  assert.deepEqual(body.allowed_values, ['RelatedTo', 'BlockedBy', 'BlockedTo'])
  assert.equal(body.code, 'invalid_field')
  assert.equal(body.field, 'relation_type')
  for (const name of body.allowed_values) assert.match(body.error, new RegExp(name))
  assert.match(taskRelationTypeHelp, /RelatedTo, BlockedBy or BlockedTo/)
  assert.match(tasks.parameters_and_caveats, /RelatedTo, BlockedBy or BlockedTo/)
  assert.match(LinkTasksInputSchema.shape.relation_type.description, /RelatedTo, BlockedBy or BlockedTo/)
  const missing = LinkTasksInputSchema.safeParse({ action: 'link', source_task_id: 1, target_task_id: 2 })
  assert.equal(missing.success, false)
  assert.match(JSON.stringify(missing.error.issues), /RelatedTo, BlockedBy or BlockedTo/)
  assert.equal(normalizeTaskRelationType('blockedby'), null)
  assert.equal(normalizeTaskRelationType('BlockedBy'), 'BlockedBy')
  assert.match(TOOL_METADATA.LINK_TASKS.description, /RelatedTo is neutral/)
  assert.match(TOOL_METADATA.LINK_TASKS.description, /BlockedBy means the source is blocked by the target/)
  assert.match(TOOL_METADATA.LINK_TASKS.description, /BlockedTo means the source blocks the target/)
})

test('marking a ticket done is a column move, not a status', async () => {
  const fields = { hasDueDate: false, parsedPullRequest: null }
  const done = await validateTaskUpdateIdentifiers({ status: 'Done' }, false, fields).json()
  assert.equal(done.code, 'invalid_field')
  assert.equal(done.field, 'status')
  assert.match(done.error, /Normal, Archive, Deleted/)
  assert.match(done.error, /Done is a column/)
  assert.match(done.error, /section/)
  const lower = await validateTaskUpdateIdentifiers({ status: 'done' }, false, fields).json()
  assert.match(lower.error, /Done is a column/)
  const other = await validateTaskUpdateIdentifiers({ status: 'Closed' }, false, fields).json()
  assert.doesNotMatch(other.error, /Done is a column/)
  assert.match(parameters.status, /Done is a column/)
  assert.match(tasks.parameters_and_caveats, /Done column/)
  assert.match(TOOL_METADATA.UPDATE_TASK.description, /edit is another name for this update/)
  assert.match(TOOL_METADATA.UPDATE_TASK.description, /set section or section_id to the Done column/)
  assert.doesNotMatch(TOOL_METADATA.UPDATE_TASK.description, /status\(column\/section\)/)
})
