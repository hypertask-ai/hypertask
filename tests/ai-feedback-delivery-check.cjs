const assert = require('node:assert/strict')
const { execFileSync } = require('node:child_process')
const path = require('node:path')
const git = (...args) => execFileSync('git', args, { encoding: 'utf8' }).trim()
const expected = 'HTPR-7195 Fail closed on free text, reject secrets, keep report history, retry lock'
assert.equal(process.cwd(), '/home/valentin/projects/hypertask-htpr-7195')
assert.equal(git('branch', '--show-current'), 'htpr-7195-ai-feedback')
assert.equal(git('log', '-1', '--format=%s'), expected)
assert.equal(git('ls-tree', 'HEAD', 'GATES.md'), '', 'The ledger must not be committed')
assert.equal(git('diff', '--cached', '--name-only'), '', 'All delivery changes must be committed')
const dirty = git('status', '--porcelain').split('\n').filter(Boolean)
assert.ok(dirty.every((line) => line === '?? GATES.md'), 'Only the untracked ledger may remain')
const base = git('merge-base', 'HEAD', 'origin/production')
execFileSync('git', ['diff', '--check', base], { stdio: 'pipe' })
const diff = git('diff', '--unified=0', base)
const additions = diff.split('\n').filter((line) => line.startsWith('+') && !line.startsWith('+++')).join('\n')
const hasEmDash = (text) => text.includes(String.fromCharCode(0x2014))
assert.equal(hasEmDash('fixture' + String.fromCharCode(0x2014)), true)
assert.equal(hasEmDash(additions), false, 'New code, comments and copy must not contain an em dash')
const files = git('diff', '--name-only', base).split('\n').filter(Boolean)
for (const file of files) {
  assert.equal(path.isAbsolute(file), false)
  assert.ok(!file.startsWith('..'))
}
assert.ok(files.includes('src/app/api/mcp/feedback/route.ts'))
assert.ok(files.includes('src/lib/aiFeedback/report.ts'))
assert.equal(files.includes('src/lib/flags/definitions/index.generated.ts'), false)
assert.ok(files.includes('src/lib/flags/definitions/htpr-7195-ai-feedback.ts'))
console.log('Local delivery verified')
